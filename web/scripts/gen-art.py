"""Generates the brand art from ONE source of truth: the pixel grids below.
   Outputs (logo only): components/pixel-data.ts, app/icon.svg, public/brand/*.png and the mod icon. The link preview picture comes from scripts/og.mjs.
   Run from web/:  python3 scripts/gen-art.py   (needs Pillow)"""
import json, os, sys
from PIL import Image, ImageDraw

PAL = {'a': '#f2c14e', 'k': '#14161a', 'g': '#5da83a', 'G': '#86d05a', 'd': '#3a6b24', 'c': '#efe6d2', 'y': '#f2c14e', 'p': '#b07cff', 'P': '#e3d0ff',
       'r': '#d9473a', 'b': '#5aa9ff', 'o': '#d98a3a', 'w': '#efe6d2', 'n': '#8a5b25'}

LOGO = [
 "................",
 ".kkkkkkkkkkk....",
 ".kGGGGGGGGGk..P.",
 ".kddggggggggk.pPp"[:16],
 ".kddgggggggk..P.",
 ".kddgkkkkkgk....",
 ".kddgkccckgk....",
 ".kddgkcyckgk....",
 ".kddgkccckgk....",
 ".kddgkkkkkgk....",
 ".kddgggggggk....",
 ".kddgggggggk....",
 ".kddgggggggk....",
 ".kddgggggggk....",
 ".kkkkkkkykkk....",
 "........y.......",
]
# normalise: every row exactly 16 wide (pad/trim) so a typo can't skew the art
LOGO = [r.ljust(16, '.')[:16] for r in LOGO]
LOGO[3] = ".kddgggggggk.pPp"


def rects(grid, cur='currentColor'):
    out = []
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch == '.': continue
            out.append([x, y, cur if ch == '#' else PAL[ch]])
    return out

# ---- TS data for the React components
with open('components/pixel-data.ts', 'w', encoding='utf-8') as f:
    f.write("// Generated by scripts/gen-art.py — edit the grids there, not here.\n")
    f.write("export const LOGO_RECTS: [number, number, string][] = " + json.dumps(rects(LOGO)) + "\n")

# ---- favicon svg
svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">' + ''.join(
    f'<rect x="{x}" y="{y}" width="1" height="1" fill="{c}"/>' for x, y, c in rects(LOGO)) + '</svg>'
open('app/icon.svg', 'w', encoding='utf-8').write(svg)

def render(grid, scale, cur=(239, 230, 210)):
    im = Image.new('RGBA', (len(grid[0]) * scale, len(grid) * scale), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    for y, x, c in [(y, x, c) for x, y, c in rects(grid, '#efe6d2')]:
        d.rectangle([x * scale, y * scale, (x + 1) * scale - 1, (y + 1) * scale - 1], fill=c)
    return im

# ---- mod / app icons
BG, EDGE = (42, 33, 25, 255), (77, 60, 43, 255)
def logo_on(size, scale, canvas):
    logo = render(LOGO, scale); o = (size - logo.width) // 2
    canvas.alpha_composite(logo, (o, o)); return canvas
def tile(size=128, scale=6):   # the square mod icon (Minecraft and Modrinth draw it as a square)
    t = Image.new('RGBA', (size, size), BG); d = ImageDraw.Draw(t)
    d.rectangle([0, 0, size - 1, size - 1], outline=(11, 8, 6, 255), width=3)
    d.rectangle([3, 3, size - 4, size - 4], outline=EDGE, width=3)
    return logo_on(size, scale, t)
def rounded(size, scale):   # the installed app icon: a rounded tile with smooth edges (drawn 4x larger, then shrunk)
    big = size * 4; m = Image.new('RGBA', (big, big), (0, 0, 0, 0)); d = ImageDraw.Draw(m)
    r = int(big * 0.22); w = max(4, big // 64)
    d.rounded_rectangle([0, 0, big - 1, big - 1], radius=r, fill=EDGE)
    d.rounded_rectangle([w, w, big - 1 - w, big - 1 - w], radius=r - w, fill=BG)
    return logo_on(size, scale, m.resize((size, size), Image.LANCZOS))
def maskable(size, scale):   # full bleed: Android cuts its own shape, so the logo sits inside the middle 80%
    return logo_on(size, scale, Image.new('RGBA', (size, size), BG))
def badge(size=96):   # the status bar icon: Android only uses the shape, so white on transparent
    scale = size // 16; b = Image.new('RGBA', (size, size), (0, 0, 0, 0)); d = ImageDraw.Draw(b)
    for y, row in enumerate(LOGO):
        for x, ch in enumerate(row):
            if ch == '.' or (ch == 'k' and 5 <= x <= 9 and 5 <= y <= 9) or ch == 'c': continue   # cut out the label window
            d.rectangle([x * scale, y * scale, (x + 1) * scale - 1, (y + 1) * scale - 1], fill=(255, 255, 255, 255))
    return b
os.makedirs('public/brand', exist_ok=True)
rounded(128, 6).save('public/brand/icon-128.png'); rounded(512, 24).save('public/brand/icon-512.png')
maskable(512, 18).save('public/brand/maskable-512.png'); badge(96).save('public/brand/badge-96.png')
maskable(180, 9).save('app/apple-icon.png')   # iOS rounds the corners itself
os.makedirs('../mod/src/main/resources/assets/survival_notebook', exist_ok=True)
tile(128, 6).save('../mod/src/main/resources/assets/survival_notebook/icon.png')
os.makedirs('../mod/src/main/resources/assets/survival_notebook/textures/gui', exist_ok=True)
render(LOGO, 1).save('../mod/src/main/resources/assets/survival_notebook/textures/gui/logo.png')   # the notebook's header icon in game, 16x16
