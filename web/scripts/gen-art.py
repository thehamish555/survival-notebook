"""Generates the brand art from ONE source of truth: the pixel grids below.
   Outputs (logo only): components/pixel-data.ts, app/icon.svg, public/brand/*.png, public/og.png, and the mod icon.
   Run from web/:  python3 scripts/gen-art.py   (needs Pillow)"""
import json, os, sys, urllib.request
from PIL import Image, ImageDraw, ImageFilter, ImageFont

PAL = {'a': '#f2c14e', 'k': '#14161a', 'g': '#5da83a', 'G': '#86d05a', 'd': '#3a6b24', 'c': '#efe6d2', 'y': '#f2c14e', 'p': '#b07cff', 'P': '#e3d0ff',
       'r': '#d9473a', 'b': '#5aa9ff', 'o': '#d98a3a', 'w': '#efe6d2', 'n': '#8a5b25'}

LOGO = [
 "................",
 ".kkkkkkkkkkk....",
 ".kGGGGGGGGGk..P.",
 ".kddggggggggk.pPp"[:16],
 ".kddgggggggk..P.",
 ".kddgkkkkkgk....",
 ".kddgkccckgk....",
 ".kddgkcyckgk....",
 ".kddgkccckgk....",
 ".kddgkkkkkgk....",
 ".kddgggggggk....",
 ".kddgggggggk....",
 ".kddgggggggk....",
 ".kddgggggggk....",
 ".kkkkkkkykkk....",
 "........y.......",
]
# normalise: every row exactly 16 wide (pad/trim) so a typo can't skew the art
LOGO = [r.ljust(16, '.')[:16] for r in LOGO]
LOGO[3] = ".kddgggggggk.pPp"


def rects(grid, cur='currentColor'):
    out = []
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch == '.': continue
            out.append([x, y, cur if ch == '#' else PAL[ch]])
    return out

# ---- TS data for the React components
with open('components/pixel-data.ts', 'w') as f:
    f.write("// Generated by scripts/gen-art.py — edit the grids there, not here.\n")
    f.write("export const LOGO_RECTS: [number, number, string][] = " + json.dumps(rects(LOGO)) + "\n")

# ---- favicon svg
svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">' + ''.join(
    f'<rect x="{x}" y="{y}" width="1" height="1" fill="{c}"/>' for x, y, c in rects(LOGO)) + '</svg>'
open('app/icon.svg', 'w').write(svg)

def render(grid, scale, cur=(239, 230, 210)):
    im = Image.new('RGBA', (len(grid[0]) * scale, len(grid) * scale), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    for y, x, c in [(y, x, c) for x, y, c in rects(grid, '#efe6d2')]:
        d.rectangle([x * scale, y * scale, (x + 1) * scale - 1, (y + 1) * scale - 1], fill=c)
    return im

# ---- mod / app icon (128px tile, pixel-perfect scale)
def tile(size=128, scale=6):
    t = Image.new('RGBA', (size, size), (42, 33, 25, 255)); d = ImageDraw.Draw(t)
    d.rectangle([0, 0, size - 1, size - 1], outline=(11, 8, 6, 255), width=3)
    d.rectangle([3, 3, size - 4, size - 4], outline=(77, 60, 43, 255), width=3)
    logo = render(LOGO, scale); o = (size - logo.width) // 2
    t.alpha_composite(logo, (o, o)); return t
