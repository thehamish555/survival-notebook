#!/usr/bin/env python3
"""Builds the sidebar/tab icons for both the mod and the website from tab-icons.json. Run after editing that file."""
import json, os, re
here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, 'tab-icons.json')))
order, icons = d['order'], d['icons']

# --- web: lib/tab-icons.ts
ts = "// Generated by shared/gen-icons.py from shared/tab-icons.json. Do not edit by hand.\nexport const TAB_ICON_ORDER = " + json.dumps(order) + "\n"
ts += "export const TAB_ICONS: Record<string, { pal: Record<string, string>; rows: string[] }> = " + json.dumps({k: icons[k] for k in order}) + "\n"
open(os.path.join(here, '..', 'web', 'lib', 'tab-icons.ts'), 'w').write(ts)

# --- mod: TabIcons.java
out = "package dev.hamish.survivalnotebook;\n\n/** Pixel icons (10x10) for the sidebar and home tiles. Generated by shared/gen-icons.py from shared/tab-icons.json. */\nfinal class TabIcons {\n\tprivate TabIcons() { }\n\n"
out += "\tstatic final String[] ORDER = {" + ", ".join('"%s"' % k for k in order) + "};\n\tstatic final int[][] PX = {\n"
for k in order:
    pal = icons[k]['pal']; flat = []
    for r in icons[k]['rows']:
        for ch in r: flat.append('0' if ch == '.' else '0xFF' + pal[ch].lstrip('#').upper())
    out += "\t\t{" + ",".join(flat) + "},   // " + k + "\n"
out += "\t};\n\n\tstatic int index(String name) { for (int i = 0; i < ORDER.length; i++) if (ORDER[i].equals(name)) return i; return 0; }\n\n"
out += "\tstatic void draw(net.minecraft.client.gui.GuiGraphicsExtractor g, String name, int x, int y) { draw(g, name, x, y, 1); }\n\n"
out += "\t/** Draws icon {@code name} at (x, y) with each icon pixel scaled to {@code s} screen pixels. */\n\tstatic void draw(net.minecraft.client.gui.GuiGraphicsExtractor g, String name, int x, int y, int s) {\n\t\tint[] px = PX[index(name)];\n\t\tfor (int k = 0; k < 100; k++) if (px[k] != 0) g.fill(x + (k % 10) * s, y + (k / 10) * s, x + (k % 10 + 1) * s, y + (k / 10 + 1) * s, px[k]);\n\t}\n}\n"
open(os.path.join(here, '..', 'mod', 'src', 'main', 'java', 'dev', 'hamish', 'survivalnotebook', 'TabIcons.java'), 'w').write(out)
print('ok')
